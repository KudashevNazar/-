def create_potions(type_names):
    """Створює 50 зілль. type_names - список назв типів інгредієнтів."""
    result = []
    count = len(type_names)
    for i in range(len(POTION_NAMES)):
        a = i % count
        b = (a + 1 + i // count) % count
        recipe = [type_names[a], type_names[b]]
        if i % 3 == 0:  # кожне третє зілля складніше - 3 типи
            c = (i * 5 + 2) % count
            while c == a or c == b:
                c = (c + 1) % count
            recipe.append(type_names[c])
        price = 20 * len(recipe) + 20 + (i * 7) % 40
        result.append({"name": POTION_NAMES[i], "recipe": recipe, "price": price})
    return result
# Інгредієнти: 8 типів x 5 назв x 5 рівнів якості = 200 різних

import random

TYPES = {
    "Трава": ["Меліса", "Полин", "Звіробій", "Чебрець", "Валеріана"],
    "Гриб": ["Мухомор", "Лисичка", "Трутовик", "Сморчок", "Опеньок"],
    "Мінерал": ["Сірка", "Селітра", "Галіт", "Кіновар", "Малахіт"],
    "Кристал": ["Аметист", "Кварц", "Берил", "Топаз", "Обсидіан"],
    "Тварина": ["Павучий шовк", "Крило кажана", "Жаб'яча ікра", "Зуб гадюки", "Перо ворона"],
    "Рідина": ["Роса місяця", "Болотна вода", "Змійна отрута", "Смола дуба", "Туман ущелини"],
    "Квітка": ["Папороть", "Лотос", "Чорна троянда", "Фіалка", "Лаванда"],
    "Корінь": ["Мандрагора", "Імбир", "Женьшень", "Цикорій", "Хрін"],
}

GRADES = ["★", "★★", "★★★", "★★★★", "★★★★★"]


def create_ingredients():
    """Створює список із 200 інгредієнтів."""
    result = []
    for type_name in TYPES:
        for base in TYPES[type_name]:
            for grade in GRADES:
                result.append({"name": base + " " + grade, "type": type_name})
    return result


def give_daily(inventory, ingredients, count):
    """Видає count випадкових інгредієнтів. Повертає (отримані, не влізли)."""
    got = []
    lost = []
    try:
        for i in range(count):
            item = random.choice(ingredients)
            if inventory.add(item["name"], 1):
                got.append(item["name"])
            else:
                lost.append(item["name"])
    except IndexError:
        print("Помилка: список інгредієнтів порожній!")
    return got, lost
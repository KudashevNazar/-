# Кінцівки гри

import config

INTRO = (f"Ти - молодий алхімік. Гільдія позичила тобі гроші на лабораторію "
         f"і вимагає {config.GOAL_GOLD} золотих. На це в тебе {config.MAX_DAYS} днів. "
         f"Щовечора треба платити оренду - {config.DAILY_RENT} зол. Вдачі!")


def no_money_for_rent(gold):
    """Програш: нема чим платити оренду."""
    if gold < config.DAILY_RENT:
        return ("ПРОГРАШ: Тобі нічим заплатити оренду. Господар викинув твої казанки "
                "на вулицю, а кар'єра алхіміка закінчилась.")
    return None


def check_end(day, gold):
    """Повертає текст кінцівки (перемога/програш) або None, якщо гра триває."""
    if gold >= config.GOAL_GOLD:
        return (f"ПЕРЕМОГА: Ти зібрав {gold} золотих за {day} дн. Борг виплачено, "
                "Гільдія вручає тобі титул Майстра-алхіміка!")
    if day >= config.MAX_DAYS:
        return (f"ПРОГРАШ: Час вийшов, а в тебе лише {gold} із {config.GOAL_GOLD} золотих. "
                "Гільдія забрала лабораторію за борги.")
    return None